"""Phase 2 live-data validation for the TikTok import.

Queries PostgreSQL directly rather than trusting the collector's own counters.
Prints a sanitized summary: no captions, no handles, no ids, no credentials —
only shapes, counts and distributions, so the output is safe to commit.

    python scripts/validate_tiktok_import.py            # sanitized (default)
    python scripts/validate_tiktok_import.py --private  # adds local-only detail
"""

from __future__ import annotations

import argparse
import os
import sys
from datetime import timezone
from pathlib import Path

from sqlalchemy import create_engine, text

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

PLATFORM = "tiktok"


def q(conn, sql: str, **p):
    return conn.execute(text(sql), p)


def one(conn, sql: str, **p):
    return conn.execute(text(sql), p).scalar()


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--private", action="store_true",
                    help="include detail that must NOT be committed")
    args = ap.parse_args()

    url = os.environ.get("VIRALLAB_DB_URL")
    if not url:
        print("VIRALLAB_DB_URL not set", file=sys.stderr)
        return 2
    eng = create_engine(url, future=True)
    out: list[str] = []

    def say(line: str = "") -> None:
        out.append(line)
        # Windows consoles are cp1252; keep stdout ASCII-safe.
        print(line.encode("ascii", "replace").decode())

    with eng.connect() as c:
        say("# TikTok live-collection validation")
        say()
        say(f"Platform: `{PLATFORM}`  generated by "
            "`scripts/validate_tiktok_import.py`")
        say()

        # ---- 1. shape -------------------------------------------------
        rows = one(c, "select count(*) from videos where platform=:p", p=PLATFORM)
        uniq = one(c, "select count(distinct external_id) from videos "
                      "where platform=:p", p=PLATFORM)
        creators = one(c, "select count(*) from creators where platform=:p",
                       p=PLATFORM)
        say("## 1. Shape")
        say()
        say("| | |")
        say("|---|---|")
        say(f"| video rows | {rows} |")
        say(f"| distinct external_id | {uniq} |")
        say(f"| duplicate external_ids | **{rows - uniq}** |")
        say(f"| creators | {creators} |")

        lo, hi = c.execute(text(
            "select min(posted_at), max(posted_at) from videos "
            "where platform=:p"), {"p": PLATFORM}).one()
        span = (hi - lo).days if lo and hi else 0
        say(f"| date range | {str(lo)[:10]} .. {str(hi)[:10]} ({span} days) |")

        snaps = one(c, "select count(*) from metrics_snapshots s "
                       "join videos v on v.id=s.video_id where v.platform=:p",
                    p=PLATFORM)
        vids_with = one(c, "select count(distinct s.video_id) "
                           "from metrics_snapshots s join videos v "
                           "on v.id=s.video_id where v.platform=:p", p=PLATFORM)
        say(f"| metric snapshots | {snaps} |")
        say(f"| videos with >=1 snapshot | {vids_with} / {rows} |")
        say(f"| videos with NO snapshot | **{rows - vids_with}** |")
        say()

        # ---- 2. completeness of each field ----------------------------
        say("## 2. NULL / empty counts per field")
        say()
        say("| field | NULL | empty | populated |")
        say("|---|---|---|---|")
        for col, has_empty in (("external_id", True), ("posted_at", False),
                               ("duration_s", False), ("caption", True),
                               ("hashtags", False), ("source", True),
                               ("media_status", True), ("creator_id", False)):
            nulls = one(c, f"select count(*) from videos where platform=:p "
                           f"and {col} is null", p=PLATFORM)
            empt = 0
            if has_empty:
                empt = one(c, f"select count(*) from videos where platform=:p "
                              f"and {col} is not null and trim({col}::text)=''",
                           p=PLATFORM)
            flag = " (!)" if (col in ("external_id", "posted_at") and nulls) else ""
            say(f"| `{col}` | {nulls}{flag} | {empt} | {rows - nulls - empt} |")

        say()
        say("Metric fields on the latest snapshot per video:")
        say()
        say("| metric | NULL | zero | populated | min | max |")
        say("|---|---|---|---|---|---|")
        for m in ("views", "likes", "comments", "shares", "saves"):
            r = c.execute(text(f"""
                with latest as (
                  select distinct on (s.video_id) s.*
                  from metrics_snapshots s join videos v on v.id=s.video_id
                  where v.platform=:p order by s.video_id, s.captured_at desc)
                select count(*) filter (where {m} is null),
                       count(*) filter (where {m} = 0),
                       count(*) filter (where {m} > 0),
                       min({m}), max({m}) from latest"""), {"p": PLATFORM}).one()
            note = " (not exposed by the Display API)" if m == "saves" else ""
            say(f"| `{m}` | {r[0]} | {r[1]} | {r[2]} | {r[3]} | {r[4]} |"
                + (f" {note}" if note else ""))
        say()

        # ---- 3. sanity / suspicious values ----------------------------
        say("## 3. Validity checks")
        say()
        checks = [
            ("posted_at in the future",
             "select count(*) from videos where platform=:p and posted_at > now()"),
            ("posted_at before TikTok existed (2016)",
             "select count(*) from videos where platform=:p "
             "and posted_at < '2016-01-01'"),
            ("duration <= 0",
             "select count(*) from videos where platform=:p and duration_s <= 0"),
            ("duration > 10 min",
             "select count(*) from videos where platform=:p and duration_s > 600"),
            ("negative metric values",
             "select count(*) from metrics_snapshots s join videos v "
             "on v.id=s.video_id where v.platform=:p and (s.views<0 or s.likes<0 "
             "or s.comments<0 or s.shares<0)"),
            ("likes > views (implausible)",
             "select count(*) from metrics_snapshots s join videos v "
             "on v.id=s.video_id where v.platform=:p and s.likes > s.views"),
            ("snapshot captured before the video was posted",
             "select count(*) from metrics_snapshots s join videos v "
             "on v.id=s.video_id where v.platform=:p and s.captured_at < v.posted_at"),
            ("snapshots flagged is_rounded (official API should be exact)",
             "select count(*) from metrics_snapshots s join videos v "
             "on v.id=s.video_id where v.platform=:p and s.is_rounded"),
            ("videos not marked source=official_api",
             "select count(*) from videos where platform=:p "
             "and source <> 'official_api'"),
        ]
        say("| check | count | verdict |")
        say("|---|---|---|")
        problems = 0
        for label, sql in checks:
            n = one(c, sql, p=PLATFORM) or 0
            problems += n
            say(f"| {label} | {n} | {'ok' if n == 0 else '**REVIEW**'} |")
        say()

        # ---- 4. metric-age distribution (the section 5.4 point) -------
        say("## 4. Metric age at capture — NOT fixed-age data")
        say()
        say("Every snapshot here is a **lifetime cumulative** reading taken at "
            "import time, not a views@7d or views@30d measurement. The age "
            "distribution below is why that distinction matters: these videos "
            "were between days and years old when first observed.")
        say()
        r = c.execute(text("""
            with firsts as (
              select distinct on (s.video_id) s.video_id, s.captured_at,
                     v.posted_at
              from metrics_snapshots s join videos v on v.id=s.video_id
              where v.platform=:p order by s.video_id, s.captured_at)
            select count(*),
                   min(extract(epoch from (captured_at-posted_at))/86400)::int,
                   max(extract(epoch from (captured_at-posted_at))/86400)::int,
                   percentile_cont(0.5) within group (
                     order by extract(epoch from (captured_at-posted_at))/86400)::int,
                   count(*) filter (where captured_at-posted_at < interval '7 days'),
                   count(*) filter (where captured_at-posted_at < interval '30 days')
            from firsts"""), {"p": PLATFORM}).one()
        say("| | |")
        say("|---|---|")
        say(f"| videos with a first snapshot | {r[0]} |")
        say(f"| age at first capture — min | {r[1]} days |")
        say(f"| age at first capture — median | {r[3]} days |")
        say(f"| age at first capture — max | {r[2]} days |")
        say(f"| captured before day 7 | {r[4]} |")
        say(f"| captured before day 30 | {r[5]} |")
        say()
        say(f"**Only {r[4]} video(s) were first observed before day 7 and "
            f"{r[5]} before day 30.** A true `views@7d` series can therefore "
            "only be built going forward, from videos posted after collection "
            "began. Treating these readings as fixed-age would measure elapsed "
            "exposure, not performance (plan section 5.4).")
        say()

        # ---- 5. collection runs ---------------------------------------
        say("## 5. Collection runs")
        say()
        runs = c.execute(text(
            "select kind, status, videos_seen, videos_new, snapshots_written, "
            "started_at, finished_at from collection_runs where platform=:p "
            "order by started_at desc limit 10"), {"p": PLATFORM}).all()
        if not runs:
            say("_none recorded_")
        else:
            say("| kind | status | seen | new | snapshots | duration |")
            say("|---|---|---|---|---|---|")
            for k, st, seen, new, sn, s0, s1 in runs:
                dur = f"{(s1-s0).total_seconds():.1f}s" if s1 else "—"
                say(f"| {k} | {st} | {seen} | {new} | {sn} | {dur} |")
        say()

        if args.private:
            print("\n--- PRIVATE (do not commit) ---")
            for ext, views, posted in c.execute(text(
                "select v.external_id, s.views, v.posted_at from videos v "
                "join metrics_snapshots s on s.video_id=v.id "
                "where v.platform=:p order by s.views desc limit 5"),
                    {"p": PLATFORM}).all():
                print(f"  {ext}  {views:>9,}  {str(posted)[:10]}")

        say("---")
        say(f"Validity problems found: **{problems}**")

    report = Path("docs/benchmarks/2-tiktok-live-validation.md")
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"\n  report -> {report}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
